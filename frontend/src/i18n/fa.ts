/**
 * `as const` above keeps the Persian source readable, but a literal-typed
 * dictionary can never be satisfied by a second language - so widen every
 * leaf back to its primitive type before other locales implement it.
 */
type Widen<T> = T extends string
  ? string
  : T extends number
    ? number
    : T extends boolean
      ? boolean
      : T extends readonly (infer U)[]
        ? readonly Widen<U>[]
        : { -readonly [K in keyof T]: Widen<T[K]> };

